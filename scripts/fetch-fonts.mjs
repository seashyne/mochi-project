// Downloads the two UI font families into mochi/public/fonts and generates the
// matching @font-face stylesheet.
//
// They were previously pulled from the Google Fonts CDN at runtime. That makes an
// external host a hard dependency of the shell - the product promise is "open a link
// and play" - and it is a privacy question the EU has already ruled on. Self-hosting
// costs about 150 KB and removes both problems.
//
// Only the thai and latin subsets are kept: the app ships en/th/ja/zh, and neither
// family covers CJK, so those correctly fall back to a system font. Skipping the
// vietnamese and latin-ext subsets halves the download for glyphs nobody requests.
//
// Run with: node scripts/fetch-fonts.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(ROOT, 'mochi', 'public', 'fonts');
const CSS_OUT = path.join(ROOT, 'mochi', 'src', 'styles', 'fonts.css');

// A modern UA is required, otherwise the API answers with legacy TTF.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  { query: 'IBM+Plex+Sans+Thai', slug: 'ibm-plex-sans-thai', name: 'IBM Plex Sans Thai', weights: [400, 500, 600] },
  { query: 'Mitr', slug: 'mitr', name: 'Mitr', weights: [500, 600] }
];

const KEEP_SUBSETS = new Set(['thai', 'latin']);

async function fetchText(url) {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return response.text();
}

async function fetchBinary(url) {
  const response = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return Buffer.from(await response.arrayBuffer());
}

/** Splits a Google Fonts stylesheet into `{ subset, block }` pairs. */
function parseBlocks(css) {
  const blocks = [];
  const pattern = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let match;
  while ((match = pattern.exec(css)) !== null) {
    blocks.push({ subset: match[1], block: match[2] });
  }
  return blocks;
}

function field(block, name) {
  const match = new RegExp(`${name}:\\s*([^;]+);`).exec(block);
  return match ? match[1].trim() : null;
}

async function main() {
  fs.mkdirSync(FONT_DIR, { recursive: true });

  const rules = [];
  let bytes = 0;

  for (const family of FAMILIES) {
    const css = await fetchText(
      `https://fonts.googleapis.com/css2?family=${family.query}:wght@${family.weights.join(';')}&display=swap`
    );

    for (const { subset, block } of parseBlocks(css)) {
      if (!KEEP_SUBSETS.has(subset)) continue;

      const weight = field(block, 'font-weight');
      const source = /url\((https:[^)]+)\)/.exec(block)?.[1];
      const unicodeRange = field(block, 'unicode-range');
      if (!weight || !source) continue;

      const file = `${family.slug}-${weight}-${subset}.woff2`;
      const binary = await fetchBinary(source);
      fs.writeFileSync(path.join(FONT_DIR, file), binary);
      bytes += binary.length;

      rules.push({
        family: family.name,
        weight,
        file,
        unicodeRange,
        license: family.slug === 'mitr' ? 'OFL-1.1' : 'OFL-1.1'
      });
      console.log(`  ${file}  ${(binary.length / 1024).toFixed(1)} KB`);
    }
  }

  // CSS has no line comments: a leading `//` makes PostCSS fail at build time.
  const header = `/* Generated by scripts/fetch-fonts.mjs - do not edit by hand.
 *
 * Self-hosted so the shell has no external font dependency: the product promise is
 * that a link opens a playable world, and a CDN in the critical path breaks that
 * behind a firewall and creates a consent question. Both families are SIL Open Font
 * License 1.1; the licence text ships in public/fonts/OFL-*.txt and is listed in
 * THIRD_PARTY_NOTICES.txt.
 *
 * Only thai and latin subsets are present. Neither family covers CJK, so ja/zh text
 * correctly falls back to a system font.
 */

`;

  const body = rules
    .map(
      (rule) => `/* ${rule.family} ${rule.weight} - ${rule.file} */
@font-face {
  font-family: '${rule.family}';
  font-style: normal;
  font-weight: ${rule.weight};
  font-display: swap;
  src: url('/fonts/${rule.file}') format('woff2');
  unicode-range: ${rule.unicodeRange};
}`
    )
    .join('\n\n');

  fs.writeFileSync(CSS_OUT, `${header}${body}\n`);
  console.log(`\n${rules.length} faces, ${(bytes / 1024).toFixed(1)} KB total`);
  console.log(`wrote ${path.relative(ROOT, CSS_OUT)}`);
}

main().catch((error) => {
  console.error(`font fetch failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
